-- Zones de rangement : numérotées de 1 à 200 (fait une seule fois).
-- Les anciennes zones « lettres » (A à Z) qui ne contiennent aucun produit sont
-- retirées ; celles qui servent encore sont conservées telles quelles.
do $$
begin
  if not exists (select 1 from public.settings where key = 'zones_numbered') then
    delete from public.zones z
      where z.name ~ '^[A-Z]$'
        and not exists (select 1 from public.products p where p.zone_id = z.id);
    insert into public.zones (name)
      select g::text from generate_series(1, 200) as g
    on conflict (name) do nothing;
    insert into public.settings (key, value) values ('zones_numbered', '1');
  end if;
end $$;

-- Texte simplifié pour la recherche : minuscules, sans accents, sans
-- ponctuation ni espaces (« Câble 3G 2,5 mm² » → « cable3g25mm2 »).
-- Doit rester identique à searchWords() dans client/src/api.js.
create or replace function public.search_norm(t text) returns text
language sql immutable as $$
  select regexp_replace(
    translate(replace(replace(lower(coalesce(t, '')), 'œ', 'oe'), 'æ', 'ae'),
      'àáâãäåçèéêëìíîïñòóôõöùúûüýÿ²³', 'aaaaaaceeeeiiiinooooouuuuyy23'),
    '[^a-z0-9]', '', 'g')
$$;
grant execute on function public.search_norm(text) to anon, authenticated;

-- Vue de lecture : produits + noms de catégorie/zone + drapeau d'alerte
drop view if exists public.products_list;
create view public.products_list
with (security_invoker = true) as
select
  p.*,
  (p.alert_threshold > 0 and p.quantity <= p.alert_threshold) as in_alert,
  c.name as category_name,
  z.name as zone_name,
  -- pour trier les zones dans l'ordre 1, 2, 3 … 10, 11 (et non 1, 10, 100, 2)
  case when z.name ~ '^[0-9]+$' then lpad(z.name, 12, '0') else z.name end as zone_sort,
  concat_ws('|', public.search_norm(p.name), public.search_norm(p.brand),
    public.search_norm(p.reference), public.search_norm(p.barcode)) as search_text
from public.products p
left join public.categories c on c.id = p.category_id
left join public.zones z on z.id = p.zone_id;

-- Vue de l'historique : mouvements + catégorie/stock du produit concerné
-- (pour pouvoir filtrer l'historique par catégorie, stock, personne…)
drop view if exists public.movements_list;
create view public.movements_list
with (security_invoker = true) as
select
  m.*,
  p.category_id,
  c.name as category_name,
  p.stock,
  public.search_norm(m.product_name) as search_text
from public.movements m
left join public.products p on p.id = m.product_id
left join public.categories c on c.id = p.category_id;

