-- ------------------------------------------------------------- FONCTIONS
-- Vérification du mot de passe d'accès à l'inscription (appelable sans compte)
create or replace function public.check_registration_password(pwd text)
returns boolean
language sql security definer stable set search_path = public
as $$
  select exists(select 1 from settings where key = 'registration_password' and value = pwd)
$$;
grant execute on function public.check_registration_password(text) to anon, authenticated;

-- Prise / remise de matériel : met à jour la quantité + journalise, en une fois
create or replace function public.adjust_quantity(pid bigint, delta double precision)
returns double precision
language plpgsql security definer set search_path = public
as $$
declare
  new_qty double precision;
  pname text;
  uname text;
begin
  if not public.is_manager() then
    raise exception 'Accès réservé aux gestionnaires';
  end if;
  update products
    set quantity = greatest(0, quantity + delta), updated_at = now()
    where id = pid
    returning quantity, name into new_qty, pname;
  if pname is null then
    raise exception 'Produit introuvable';
  end if;
  select display_name into uname from profiles where id = auth.uid();
  insert into movements (product_id, product_name, user_name, action, delta, quantity_after)
    values (pid, pname, coalesce(uname, '?'), case when delta > 0 then 'entrée' else 'sortie' end, delta, new_qty);
  return new_qty;
end $$;
grant execute on function public.adjust_quantity(bigint, double precision) to authenticated;

-- Restauration d'une sauvegarde (remplace tout sauf les comptes)
create or replace function public.import_backup(payload jsonb)
returns void
language plpgsql security definer set search_path = public
as $$
declare uname text;
begin
  if not public.is_admin() then
    raise exception 'Accès réservé à l''administrateur';
  end if;

  delete from movements;
  delete from products;
  delete from categories;
  delete from zones;

  insert into categories (id, name)
    select id, name from jsonb_populate_recordset(null::categories, payload->'categories');
  insert into zones (id, name)
    select id, name from jsonb_populate_recordset(null::zones, payload->'zones');
  insert into products (id, name, brand, reference, barcode, photo, unit, quantity, stock, category_id, zone_id, sub_zone, alert_threshold, created_at, updated_at)
    select id, name, brand, reference, barcode, photo, unit, quantity, stock, category_id, zone_id, sub_zone, alert_threshold, created_at, updated_at
    from jsonb_populate_recordset(null::products, payload->'products');
  insert into movements (id, product_id, product_name, user_name, action, delta, quantity_after, details, created_at)
    select id, product_id, product_name, user_name, action, delta, quantity_after, details, created_at
    from jsonb_populate_recordset(null::movements, payload->'movements');

  insert into settings (key, value)
    select key, value from jsonb_populate_recordset(null::settings, payload->'settings')
    on conflict (key) do update set value = excluded.value;

  perform setval(pg_get_serial_sequence('categories', 'id'), coalesce((select max(id) from categories), 0) + 1, false);
  perform setval(pg_get_serial_sequence('zones', 'id'), coalesce((select max(id) from zones), 0) + 1, false);
  perform setval(pg_get_serial_sequence('products', 'id'), coalesce((select max(id) from products), 0) + 1, false);
  perform setval(pg_get_serial_sequence('movements', 'id'), coalesce((select max(id) from movements), 0) + 1, false);

  select display_name into uname from profiles where id = auth.uid();
  insert into movements (product_name, user_name, action, details)
    values ('—', coalesce(uname, '?'), 'import',
            'Sauvegarde restaurée (' || coalesce(jsonb_array_length(payload->'products'), 0) || ' produits)');
end $$;
grant execute on function public.import_backup(jsonb) to authenticated;

