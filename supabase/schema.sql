-- ----------------------------------------------------------------- PROFILS
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  display_name text not null,
  role text not null default 'lecteur' check (role in ('admin','gestionnaire','lecteur')),
  status text not null default 'pending' check (status in ('pending','active','disabled')),
  created_at timestamptz not null default now()
);

-- Le tout premier compte créé devient automatiquement administrateur actif.
create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare n int;
begin
  select count(*) into n from public.profiles;
  insert into public.profiles (id, username, display_name, role, status)
  values (
    new.id,
    lower(coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1))),
    coalesce(new.raw_user_meta_data->>'display_name', 'Utilisateur'),
    case when n = 0 then 'admin' else 'lecteur' end,
    case when n = 0 then 'active' else 'pending' end
  );
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ------------------------------------------------------- FONCTIONS DE RÔLE
create or replace function public.is_active()
returns boolean language sql security definer stable set search_path = public
as $$ select exists(select 1 from profiles where id = auth.uid() and status = 'active') $$;

create or replace function public.is_manager()
returns boolean language sql security definer stable set search_path = public
as $$ select exists(select 1 from profiles where id = auth.uid() and status = 'active' and role in ('admin','gestionnaire')) $$;

create or replace function public.is_admin()
returns boolean language sql security definer stable set search_path = public
as $$ select exists(select 1 from profiles where id = auth.uid() and status = 'active' and role = 'admin') $$;

-- ----------------------------------------------------------------- TABLES
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table if not exists public.zones (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  brand text,
  reference text,
  barcode text,
  photo text,
  unit text not null default 'pièce',
  quantity double precision not null default 0,
  stock int not null default 1 check (stock in (1,2)),
  category_id bigint references public.categories(id) on delete set null,
  zone_id bigint references public.zones(id) on delete set null,
  sub_zone text,
  alert_threshold double precision not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
