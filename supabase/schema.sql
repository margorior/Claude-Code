-- ----------------------------------------------------------------- TÂCHES
-- Une tâche est créée par l'administrateur puis attribuée à une personne.
--   status    : todo (à faire) → doing (en cours) → done (terminée)
--   seen_at   : moment où la personne a ouvert la tâche (sinon « pas encore vue »)
--   closed_at : tâche clôturée par l'administrateur (archivée, photos supprimées)
--   checklist : [{ "id": "…", "text": "…", "done": true }]
--   photos    : ["<id tâche>/<fichier>", …] dans le dossier « task-photos »
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  location text,
  status text not null default 'todo' check (status in ('todo','doing','done')),
  assignee_id uuid references public.profiles(id) on delete set null,
  start_date date,
  due_date date,
  checklist jsonb not null default '[]'::jsonb,
  photos jsonb not null default '[]'::jsonb,
  position double precision not null default 0,
  seen_at timestamptz,
  done_at timestamptz,
  closed_at timestamptz,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_tasks_assignee on public.tasks (assignee_id);
create index if not exists idx_tasks_open on public.tasks (closed_at) where closed_at is null;

-- Garde-fou : la personne à qui la tâche est attribuée peut seulement changer
-- son avancement (statut, check-list, photos, « vue ») ; le reste est réservé
-- à l'administrateur.
create or replace function public.tasks_guard()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.created_by := coalesce(new.created_by, auth.uid());
    if new.status = 'done' and new.done_at is null then new.done_at := now(); end if;
    -- une tâche que l'on se donne à soi-même est forcément « vue »
    if new.assignee_id = auth.uid() and new.seen_at is null then new.seen_at := now(); end if;
    return new;
  end if;

  if auth.uid() is not null and not public.is_admin() then
    if old.closed_at is not null then
      raise exception 'Cette tâche est clôturée';
    end if;
    new.title := old.title;
    new.description := old.description;
    new.location := old.location;
    new.assignee_id := old.assignee_id;
    new.start_date := old.start_date;
    new.due_date := old.due_date;
    new.position := old.position;
    new.closed_at := old.closed_at;
    new.created_by := old.created_by;
    new.created_at := old.created_at;
  end if;

  -- Tâche confiée à quelqu'un d'autre : elle redevient « pas encore vue »
  if new.assignee_id is distinct from old.assignee_id then
    new.seen_at := case when new.assignee_id = auth.uid() then now() end;
  end if;
  if new.status = 'done' and old.status <> 'done' then
    new.done_at := now();
  elsif new.status <> 'done' then
    new.done_at := null;
  end if;
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists tasks_guard on public.tasks;
create trigger tasks_guard
  before insert or update on public.tasks
  for each row execute function public.tasks_guard();

