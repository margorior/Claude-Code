-- Marques et références : toujours en MAJUSCULES et sans espaces en trop, pour
-- ne plus avoir « Legrand » et « LEGRAND » en double dans les filtres et le tri.
-- Doit rester identique à upperClean() dans client/src/lib/text.js.
create or replace function public.upper_clean(t text) returns text
language sql immutable as $$
  select nullif(upper(btrim(regexp_replace(coalesce(t, ''), '\s+', ' ', 'g'))), '')
$$;

create or replace function public.products_normalize() returns trigger
language plpgsql as $$
begin
  new.brand := public.upper_clean(new.brand);
  new.reference := public.upper_clean(new.reference);
  return new;
end $$;

drop trigger if exists products_normalize on public.products;
create trigger products_normalize
  before insert or update on public.products
  for each row execute function public.products_normalize();

-- Mise en majuscules des produits déjà enregistrés
update public.products
  set brand = public.upper_clean(brand), reference = public.upper_clean(reference)
  where brand is distinct from public.upper_clean(brand)
     or reference is distinct from public.upper_clean(reference);

